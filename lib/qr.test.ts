import { describe, expect, it } from 'vitest';
import { qrSvg, tableScanUrl } from './qr';

/**
 * These tests exist because the thing this module replaced was not broken in
 * a way anyone noticed. QrChip rendered a convincing QR-shaped pattern for
 * years of demo use and decoded to nothing, and no test caught it because
 * there was nothing to catch: the output was not wrong, it was meaningless.
 *
 * A test cannot easily prove "this decodes", because decoding needs a camera
 * or an image pipeline. What it can prove is that the output has the shape a
 * real encoder produces -- a viewBox whose dimensions are a legal QR version
 * size -- and that the text going in is the text the card is supposed to
 * carry. That closes the gap that was actually open: an encoder that was
 * never called, and a URL that was never built.
 */

/** Every QR version's module count, from version 1 to version 40. */
function legalSize(size: number): boolean {
  return size >= 21 && size <= 177 && (size - 21) % 4 === 0;
}

const viewBoxOf = (svg: string): number => {
  const match = svg.match(/viewBox="0 0 (\d+) \d+"/);
  return match ? Number(match[1]) : -1;
};

describe('tableScanUrl', () => {
  it('points at the scan route, not the menu', () => {
    // The whole scheme depends on this. /menu?s=<slug> would be a shareable
    // link that names the restaurant in plaintext; /t/<token> is unguessable
    // and bound to one table.
    expect(tableScanUrl('https://example.com', 'abc123')).toBe(
      'https://example.com/t/abc123'
    );
  });

  it('does not double up slashes when the origin ends in one', () => {
    expect(tableScanUrl('https://example.com/', 'tok')).toBe('https://example.com/t/tok');
  });

  it('encodes a hostile token instead of letting it rewrite the path', () => {
    // A token is generated by us and is always hex, but the function takes
    // text. If a value ever arrived with a slash or a query string in it,
    // an unencoded interpolation would turn one table's code into a
    // different route.
    expect(tableScanUrl('https://example.com', '../../admin?x=1')).toBe(
      'https://example.com/t/..%2F..%2Fadmin%3Fx%3D1'
    );
  });
});

describe('qrSvg', () => {
  it('returns null for empty input rather than drawing nothing', async () => {
    // A blank code is a bug the screen should be able to see and react to.
    // Silently emitting an empty symbol would print a card that scans as
    // garbage with no hint as to why.
    expect(await qrSvg('')).toBeNull();
  });

  it('produces an svg sized like a real QR version', async () => {
    const svg = await qrSvg('https://example.com/t/abc123');
    expect(svg).toBeTypeOf('string');
    expect(legalSize(viewBoxOf(svg!))).toBe(true);
  });

  it('makes a bigger symbol for a longer url, because the version grew', async () => {
    // If this ever stops holding, the encoder is producing a fixed-size
    // grid -- which is exactly what the old fake did.
    const short = await qrSvg('https://a.co/t/1');
    const long = await qrSvg(`https://example.com/t/${'f'.repeat(64)}`);
    expect(viewBoxOf(long!)).toBeGreaterThan(viewBoxOf(short!));
  });

  it('is deterministic for the same text', async () => {
    // Not required by the spec, but a code that changed between two renders
    // of the same card would make print output unreproducible.
    const url = 'https://example.com/t/same';
    expect(await qrSvg(url)).toBe(await qrSvg(url));
  });

  it('produces different symbols for different tables', async () => {
    const a = await qrSvg('https://example.com/t/aaa');
    const b = await qrSvg('https://example.com/t/bbb');
    expect(a).not.toBe(b);
  });

  it('paints a white background so the symbol survives a dark page', async () => {
    // A transparent-background QR renders as black on black on a dark
    // surface and becomes unscannable. There is no test for "looks right",
    // but there is one for "the light module is actually there".
    const svg = await qrSvg('https://example.com/t/abc');
    // The encoder normalises #ffffffff to #ffffff; assert what it emits.
    expect(svg).toContain('fill="#ffffff"');
  });
});
