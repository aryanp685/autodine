import { QrChip } from '@/components/ui';

/**
 * A table's QR code.
 *
 * There are two paths here and the difference between them matters.
 *
 * When `svg` is present it is a real, scannable code, produced by the encoder
 * in lib/qr.ts from the URL the card will actually carry. That is the live
 * case, and it is the only one that ends up on a printed card.
 *
 * When it is absent -- no database, so the screen is showing its demo floor
 * plan -- the fallback is QrChip, which draws a QR-*shaped* pattern and
 * decodes to nothing. That is deliberate for a mock and indefensible on a
 * real table, which is why the fallback is only ever reached in demo mode,
 * where the screen says so in as many words directly above it.
 *
 * ON dangerouslySetInnerHTML
 *
 * The SVG is generated by us, from a URL we build, by a library we call. It
 * is not user content and never contains user content -- there is no path
 * from anything a restaurant can type to this string. It is injected rather
 * than parsed into React elements because the encoder emits one <svg> with a
 * path inside, and rebuilding that as a component tree would mean
 * reimplementing the renderer for no gain.
 */
export function TableQr({
  svg,
  fallbackValue,
  size = 72,
}: {
  svg?: string | null;
  fallbackValue: string;
  size?: number;
}) {
  if (!svg) {
    return <QrChip value={fallbackValue} size={size} />;
  }

  return (
    <span
      className="block [&>svg]:block [&>svg]:size-full"
      style={{ width: size, height: size }}
      // Generated server-side by lib/qr.ts; see the note above.
      dangerouslySetInnerHTML={{ __html: svg }}
    />
  );
}
